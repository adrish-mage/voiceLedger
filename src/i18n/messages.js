const keys = Object.keys(messages.en);
for (const [language, table] of Object.entries(messages)) {
  if (keys.some((key) => typeof table[key] !== 'string')) {
    throw new Error(`Incomplete message table for ${language}`);
  }
}

export function render(key, params = {}, lang = 'en') {
  const template = messages[lang]?.[key] ?? messages.en[key] ?? key;
  return template.replace(/\{([a-zA-Z][a-zA-Z0-9_]*)\}/g, (_, name) => String(params[name] ?? ''));
}

export function formatMoney(amount, currency = process.env.CURRENCY || 'INR', lang = 'en') {
  const locale = locales[lang] ?? locales.en;
  return new Intl.NumberFormat(locale, {
    style: 'currency',
    currency: String(currency).toUpperCase(),
    maximumFractionDigits: 0,
  }).format(amount);
}
